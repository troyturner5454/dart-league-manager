create table if not exists public.players (
  id bigint generated by default as identity primary key,
  name text not null,
  pin text not null,
  team text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.stats (
  id bigint generated by default as identity primary key,
  player_id bigint not null
    references public.players(id)
    on delete cascade,
  match_date date not null,
  score180 integer not null default 0,
  score140 integer not null default 0,
  score171 integer not null default 0,
  score133 integer not null default 0,
  high_score integer not null default 0,
  high_checkout integer not null default 0,
  created_at timestamptz not null default now(),

  constraint stats_score180_nonnegative
    check (score180 >= 0),

  constraint stats_score140_nonnegative
    check (score140 >= 0),

  constraint stats_score171_nonnegative
    check (score171 >= 0),

  constraint stats_score133_nonnegative
    check (score133 >= 0),

  constraint stats_high_score_range
    check (
      high_score = 0
      or high_score between 1 and 177
    ),

  constraint stats_high_checkout_range
    check (
      high_checkout = 0
      or high_checkout between 1 and 170
    ),

  constraint stats_player_date_unique
    unique (player_id, match_date)
);

create index if not exists
  stats_player_id_index
on public.stats(player_id);

create index if not exists
  stats_match_date_index
on public.stats(match_date);

create or replace function public.merge_nightly_stats(
  p_player_id bigint,
  p_match_date date,
  p_score180 integer,
  p_score140 integer,
  p_score171 integer,
  p_score133 integer,
  p_high_score integer,
  p_high_checkout integer
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if (
    p_score180 < 0
    or p_score140 < 0
    or p_score171 < 0
    or p_score133 < 0
  ) then
    raise exception
      'Dart counters cannot be negative.';
  end if;

  if (
    p_high_score < 0
    or p_high_score > 177
  ) then
    raise exception
      'High Score is outside the allowed range.';
  end if;

  if (
    p_high_checkout < 0
    or p_high_checkout > 170
  ) then
    raise exception
      'High Checkout is outside the allowed range.';
  end if;

  insert into public.stats (
    player_id,
    match_date,
    score180,
    score140,
    score171,
    score133,
    high_score,
    high_checkout
  )
  values (
    p_player_id,
    p_match_date,
    p_score180,
    p_score140,
    p_score171,
    p_score133,
    p_high_score,
    p_high_checkout
  )
  on conflict (player_id, match_date)
  do update set
    score180 =
      coalesce(public.stats.score180, 0)
      + excluded.score180,

    score140 =
      coalesce(public.stats.score140, 0)
      + excluded.score140,

    score171 =
      coalesce(public.stats.score171, 0)
      + excluded.score171,

    score133 =
      coalesce(public.stats.score133, 0)
      + excluded.score133,

    high_score = greatest(
      coalesce(public.stats.high_score, 0),
      excluded.high_score
    ),

    high_checkout = greatest(
      coalesce(public.stats.high_checkout, 0),
      excluded.high_checkout
    );
end;
$$;

